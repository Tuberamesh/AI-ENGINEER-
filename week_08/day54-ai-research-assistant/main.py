import json
import logging
import ollama
import day53_tools

MODEL = "qwen2.5:3b"
MAX_STEPS = 5

logging.basicConfig(level=logging.INFO, format="%(levelname)s: %(message)s")

# Basic conversation memory
memory = {
    "history": [],
    "tool_observations": []
}

SYSTEM_PROMPT = """
You are an AI Research Assistant.

You can use three tools:
1. calculator: mathematical calculations
2. database_search: search customer and order records by customer name
3. document_search: search local text documents by keyword

Rules:
- Use tools when the question requires calculations, database records,
  or document information.
- Never invent tool results.
- For multi-step questions, use tools in the correct order.
- Read tool results before answering.
- If a tool fails, explain the failure honestly.
- Give clear, concise answers.
- All database amounts are in INR. Always use ₹, never $.
- Base every factual claim on actual tool results.
- Do not claim an action succeeded unless the tool confirms it.
"""

# Tool definitions exposed to the LLM
TOOLS = [
    {
        "type": "function",
        "function": {
            "name": "calculator",
            "description": "Perform arithmetic on exactly two numbers.",
            "parameters": {
                "type": "object",
                "properties": {
                    "operation": {
                        "type": "string",
                        "enum": ["add", "subtract", "multiply", "divide"]
                    },
                    "numbers": {
                        "type": "array",
                        "items": {"type": "number"},
                        "minItems": 2,
                        "maxItems": 2
                    }
                },
                "required": ["operation", "numbers"]
            }
        }
    },
    {
        "type": "function",
        "function": {
            "name": "database_search",
            "description": "Search customer and order records using a customer name.",
            "parameters": {
                "type": "object",
                "properties": {
                    "keyword": {"type": "string"}
                },
                "required": ["keyword"]
            }
        }
    },
    {
        "type": "function",
        "function": {
            "name": "document_search",
            "description": "Search local text documents using a keyword.",
            "parameters": {
                "type": "object",
                "properties": {
                    "keyword": {"type": "string"}
                },
                "required": ["keyword"]
            }
        }
    }
]


def execute_agent_tool(name, arguments):
    """Validate and execute only approved tool arguments."""

    schemas = {
        "calculator": {"operation", "numbers"},
        "database_search": {"keyword"},
        "document_search": {"keyword"}
    }

    if name not in schemas:
        return {"success": False, "error": "Tool is not allowed."}

    if not isinstance(arguments, dict):
        return {"success": False, "error": "Invalid tool arguments."}

    # Remove unexpected arguments generated by the LLM
    clean_arguments = {
        key: value
        for key, value in arguments.items()
        if key in schemas[name]
    }

    required = schemas[name]

    if set(clean_arguments) != required:
        return {
            "success": False,
            "error": "Missing required or invalid tool arguments."
        }

    try:
        return day53_tools.execute_tool(name, **clean_arguments)
    except Exception as error:
        logging.exception("Tool execution failed")
        return {
            "success": False,
            "error": f"Tool execution failed: {type(error).__name__}"
        }


def run_agent(user_question):
    """Run the LLM → tool → observation → LLM loop."""

    messages = [
        {"role": "system", "content": SYSTEM_PROMPT}
    ]

    # Add recent conversation memory
    messages.extend(memory["history"][-6:])
    messages.append({"role": "user", "content": user_question})

    observations = []
    final_answer = None

    for step in range(MAX_STEPS):
        logging.info("Agent step %s/%s", step + 1, MAX_STEPS)

        try:
            response = ollama.chat(
                model=MODEL,
                messages=messages,
                tools=TOOLS
            )
        except Exception as error:
            final_answer = (
                f"Could not communicate with Ollama: "
                f"{type(error).__name__}: {error}"
            )
            break

        assistant_message = response.message
        tool_calls = assistant_message.tool_calls or []

        # No tool call means the LLM has produced its answer
        if not tool_calls:
            final_answer = assistant_message.content
            break

        messages.append(assistant_message)

        for tool_call in tool_calls:
            name = tool_call.function.name
            arguments = tool_call.function.arguments

            logging.info("Selected tool: %s | Arguments: %s", name, arguments)

            result = execute_agent_tool(name, arguments)

            observation = {
                "tool": name,
                "arguments": arguments,
                "result": result
            }

            observations.append(observation)
            memory["tool_observations"].append(observation)

            messages.append({
                "role": "tool",
                "tool_name": name,
                "content": json.dumps(result, default=str)
            })

    # If the agent reached its limit, ask for a safe summary
    if final_answer is None:
        try:
            messages.append({
                "role": "system",
                "content": (
                    "The tool execution limit has been reached. "
                    "Give the best answer using only the observations "
                    "already available. Clearly mention anything unfinished."
                )
            })

            response = ollama.chat(
                model=MODEL,
                messages=messages
            )
            final_answer = response.message.content

        except Exception:
            final_answer = (
                "I reached the execution limit before completing the task. "
                "Please simplify the question."
            )

    # Store the conversation for basic memory
    memory["history"].append({
        "role": "user",
        "content": user_question
    })
    memory["history"].append({
        "role": "assistant",
        "content": final_answer
    })

    return final_answer, observations


def main():
    # Create the Day 53 SQLite database if it doesn't exist
    day53_tools.initialize_database()

    print("\n====================================")
    print("       AI RESEARCH ASSISTANT")
    print("====================================")
    print("Model:", MODEL)
    print("Type 'exit' to quit.")
    print("Type 'memory' to inspect conversation memory.\n")

    while True:
        question = input("\nYou: ").strip()

        if question.lower() in ["exit", "quit"]:
            print("Assistant: Goodbye!")
            break

        if not question:
            continue

        if question.lower() == "memory":
            print(json.dumps(memory, indent=2, default=str))
            continue

        answer, observations = run_agent(question)

        print("\nAssistant:", answer)

        if observations:
            print("\nTools used:")
            for item in observations:
                print("-", item["tool"], item["arguments"])


if __name__ == "__main__":
    main()
